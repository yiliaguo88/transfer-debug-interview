-- Execute while connected to the transferdb database.

create table public.account
(
    balance numeric(38, 2),
    id      bigint not null
        primary key,
    name    varchar(255)
);

alter table public.account
    owner to transfer;

create table public.ledger
(
    amount      numeric(38, 2),
    account_id  bigint,
    created_at  timestamp(6),
    id          bigint generated by default as identity
        primary key,
    transfer_id bigint,
    type        varchar(255)
);

alter table public.ledger
    owner to transfer;

create table public.transfer_record
(
    amount          numeric(38, 2),
    created_at      timestamp(6),
    from_account_id bigint,
    id              bigint generated by default as identity
        primary key,
    to_account_id   bigint,
    request_id      varchar(255),
    status          varchar(255)
);

alter table public.transfer_record
    owner to transfer;
